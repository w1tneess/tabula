#requires -Version 5.1
<#
Bundles src/ and config/ into dist/tabula.ps1 (+ .sha256).
Order: Tabula.ps1 param block, build info, config, XAML, Core/*.ps1, UI/UI.ps1, rest of Tabula.ps1.
#>
[CmdletBinding()]
param([string]$OutDir)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$root = $PSScriptRoot
# $PSScriptRoot is empty inside param defaults on 5.1, so resolve it here.
if (-not $OutDir) { $OutDir = Join-Path $root 'dist' }
$marker = '# @@BUNDLE@@'

function Read-SourceFile {
    param([string]$Path)
    $text = [IO.File]::ReadAllText($Path)
    # A bare iex or an old-codepage read can mangle non-ASCII, so sources stay ASCII.
    if ($text -match '[^\x00-\x7F]') { throw "Non-ASCII character in $Path" }
    $text.TrimEnd("`r", "`n")
}

function ConvertTo-HereString {
    param([string]$Text, [string]$Name)
    # A line starting with '@ would end the here-string early.
    if ($Text -match "(?m)^'@") { throw "$Name contains a line starting with '@" }
    "@'`n$Text`n'@"
}

# Config checks. Full JSON-schema validation arrives in M2 (Test-Json is PS 7 only).
$config = foreach ($f in 'apps', 'tweaks', 'presets') {
    $path = Join-Path $root "config\$f.json"
    $text = Read-SourceFile $path
    $obj = $text | ConvertFrom-Json
    if ($obj.schemaVersion -ne 1) { throw "$f.json: schemaVersion must be 1" }
    if ($null -eq $obj.PSObject.Properties[$f]) { throw "$f.json: missing '$f' array" }
    [pscustomobject]@{ Name = "$f.json"; Text = $text }
}

$version = (Read-SourceFile (Join-Path $root 'VERSION')).Trim()
$commit = 'nogit'
try { $c = git -C $root rev-parse --short HEAD 2>$null; if ($LASTEXITCODE -eq 0 -and $c) { $commit = $c } } catch { }
$built = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss', [Globalization.CultureInfo]::InvariantCulture) + 'Z'

$entry = (Read-SourceFile (Join-Path $root 'src\Tabula.ps1')) -split "\r?\n"
$markerAt = [array]::IndexOf($entry, $marker)
if ($markerAt -lt 0) { throw "Marker '$marker' not found in src/Tabula.ps1" }
$head = $entry[0..($markerAt - 1)] -join "`n"
$tail = $entry[($markerAt + 1)..($entry.Count - 1)] -join "`n"

$bundle = New-Object System.Collections.Generic.List[string]
$bundle.Add("# Tabula $version | built $built | commit $commit")
$bundle.Add('# Clean slate, on demand. Generated by build.ps1, do not edit.')
$bundle.Add($head)
$bundle.Add("`$script:TabulaBuild = @{ Version = '$version'; Built = '$built'; Commit = '$commit' }")
$bundle.Add('$script:TabulaConfig = @{}')
foreach ($c in $config) {
    $bundle.Add("`$script:TabulaConfig['$($c.Name)'] = " + (ConvertTo-HereString $c.Text $c.Name))
}
$bundle.Add('$script:TabulaXaml = @{}')
foreach ($x in (Get-ChildItem (Join-Path $root 'src\UI') -Filter *.xaml -Recurse -ErrorAction SilentlyContinue)) {
    $bundle.Add("`$script:TabulaXaml['$($x.Name)'] = " + (ConvertTo-HereString (Read-SourceFile $x.FullName) $x.Name))
}
foreach ($f in (Get-ChildItem (Join-Path $root 'src\Core') -Filter *.ps1 | Sort-Object Name)) { $bundle.Add((Read-SourceFile $f.FullName)) }
$bundle.Add((Read-SourceFile (Join-Path $root 'src\UI\UI.ps1')))
$bundle.Add($tail)

New-Item -ItemType Directory -Force $OutDir | Out-Null
$out = Join-Path $OutDir 'tabula.ps1'
$content = ($bundle -join "`n") + "`n"
[IO.File]::WriteAllText($out, $content, (New-Object Text.UTF8Encoding($false)))

# The shipped file must parse on the PowerShell that runs this build (5.1 in CI and on Windows).
$errors = $null
[void][Management.Automation.Language.Parser]::ParseFile($out, [ref]$null, [ref]$errors)
if ($errors) { $errors | ForEach-Object { Write-Error $_.ToString() -ErrorAction Continue }; throw 'dist/tabula.ps1 does not parse' }

$hash = (Get-FileHash $out -Algorithm SHA256).Hash.ToLower()
[IO.File]::WriteAllText("$out.sha256", "$hash  tabula.ps1`n", (New-Object Text.UTF8Encoding($false)))
Write-Output "Built $out ($version, $commit)"
